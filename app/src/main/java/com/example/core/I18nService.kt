package com.example.core

import android.content.Context
import org.json.JSONObject

data class LanguageInfo(
    val code: String,
    val nativeName: String,
    val englishName: String
)

/**
 * Internationalization service supporting 17 languages loaded from assets/i18n/<lang>.json
 * with parameter interpolation ({{count}}, {{min}}, etc.).
 * Numbers inside math questions are never translated.
 *
 * Guarantees that `t(key)` NEVER returns a raw dotted translation key:
 * 1. Active language map (from assets/i18n/<code>.json)
 * 2. English fallback map (from assets/i18n/en.json)
 * 3. Built-in DEFAULT_EN map
 * 4. Human-readable title-cased fallback derived from the key suffix
 */
class I18nService(private val context: Context?) {

    private var currentCode: String = "en"
    private val cache = mutableMapOf<String, Map<String, String>>()
    private val enMap: Map<String, String> by lazy { loadLanguageMap("en") }
    private var activeMap: Map<String, String> = loadLanguageMap("en")

    fun setLanguage(code: String) {
        currentCode = code
        activeMap = loadLanguageMap(code)
    }

    fun getLanguage(): String = currentCode

    fun getLoadedMap(code: String): Map<String, String> = loadLanguageMap(code)

    fun t(key: String, params: Map<String, String> = emptyMap()): String {
        var template = activeMap[key]?.takeIf { it.isNotBlank() }
            ?: enMap[key]?.takeIf { it.isNotBlank() }
            ?: DEFAULT_EN[key]?.takeIf { it.isNotBlank() }
            ?: humanizeKey(key)
        for ((k, v) in params) {
            template = template.replace("{{$k}}", v)
        }
        return template
    }

    private fun loadLanguageMap(code: String): Map<String, String> {
        cache[code]?.let { return it }
        val ctx = context ?: return DEFAULT_EN
        return runCatching {
            val jsonText = ctx.assets.open("i18n/$code.json").bufferedReader().use { it.readText() }
            val obj = JSONObject(jsonText)
            val map = mutableMapOf<String, String>()
            map.putAll(DEFAULT_EN)
            val keys = obj.keys()
            while (keys.hasNext()) {
                val k = keys.next()
                val v = obj.optString(k, "")
                if (v.isNotBlank()) {
                    map[k] = v
                }
            }
            cache[code] = map
            map
        }.getOrDefault(DEFAULT_EN)
    }

    companion object {
        fun humanizeKey(key: String): String {
            if (!key.contains('.')) return key
            val suffix = key.substringAfterLast('.')
                .replace('_', ' ')
                .trim()
            if (suffix.isEmpty()) return key
            return suffix.replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
        }

